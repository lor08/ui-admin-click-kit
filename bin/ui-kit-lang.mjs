#!/usr/bin/env node
/**
 * Writes the kit's words as Laravel lang files, so a Laravel host serves
 * them through its own translator and its lang tests see them as files:
 *
 *   ui-kit-lang <lang-dir> [--groups ui,ui_kit] [--check]
 *
 * For every locale the package ships (lang/<locale>/<group>.json) it
 * writes <lang-dir>/<locale>/<group>.php. `--check` writes nothing and
 * exits 1 when a file is missing or differs, for a host's CI after a bump.
 * Plain JavaScript on purpose: Node does not strip types in node_modules.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8'));

const quote = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function phpArray(tree, depth) {
    const pad = '    '.repeat(depth);
    const lines = Object.entries(tree).map(([key, value]) =>
        typeof value === 'string' ? `${pad}${quote(key)} => ${quote(value)},` : `${pad}${quote(key)} => ${phpArray(value, depth + 1)},`,
    );

    return lines.length === 0 ? '[]' : `[\n${lines.join('\n')}\n${'    '.repeat(depth - 1)}]`;
}

/** The PHP file for one group of one locale, exactly as it is written. */
export function renderPhp(tree) {
    return [
        '<?php',
        '',
        'declare(strict_types=1);',
        '',
        `// Generated by ui-kit-lang from ui-admin-click-kit ${version}. Change the words`,
        '// in the package and run the command again; an edit here is overwritten.',
        `return ${phpArray(tree, 1)};`,
        '',
    ].join('\n');
}

export function plan(langDir, groups) {
    const locales = readdirSync(join(packageRoot, 'lang')).sort();

    return locales.flatMap((locale) =>
        groups
            .filter((group) => existsSync(join(packageRoot, 'lang', locale, `${group}.json`)))
            .map((group) => ({
                path: join(langDir, locale, `${group}.php`),
                content: renderPhp(JSON.parse(readFileSync(join(packageRoot, 'lang', locale, `${group}.json`), 'utf8'))),
            })),
    );
}

function main(argv) {
    const check = argv.includes('--check');
    const groupsAt = argv.indexOf('--groups');
    const groups = groupsAt === -1 ? ['ui', 'ui_kit'] : (argv[groupsAt + 1] ?? '').split(',').filter((group) => group !== '');
    const langDir = argv.find((arg, index) => !arg.startsWith('--') && argv[index - 1] !== '--groups');
    if (langDir === undefined || groups.length === 0) {
        console.error('usage: ui-kit-lang <lang-dir> [--groups ui,ui_kit] [--check]');
        return 2;
    }

    const stale = [];
    for (const file of plan(resolve(langDir), groups)) {
        const current = existsSync(file.path) ? readFileSync(file.path, 'utf8') : null;
        if (current === file.content) {
            continue;
        }
        if (check) {
            stale.push(file.path);
        } else {
            mkdirSync(dirname(file.path), { recursive: true });
            writeFileSync(file.path, file.content);
            console.log(`wrote ${file.path}`);
        }
    }
    if (stale.length > 0) {
        console.error(`stale, run ui-kit-lang ${langDir}:\n${stale.join('\n')}`);
        return 1;
    }
    if (check) {
        console.log('lang files are current');
    }

    return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}
