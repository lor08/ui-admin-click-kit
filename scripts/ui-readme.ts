/**
 * Writes src/ui/README.md from the manifest and the English words of
 * lang/en/ui_kit.json: the catalogue a person reads before writing markup.
 * `npm run ui:readme` rewrites it; tests/ui/manifest.spec.ts fails when
 * the file on disk differs from what this script would write, so the
 * catalogue cannot go stale.
 *
 *   node scripts/ui-readme.ts            writes the file
 *   node scripts/ui-readme.ts --check    exits 1 when the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { kitGroups, manifest } from '../src/showcase/manifest.ts';

export type LangTree = { [key: string]: string | LangTree };

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const readmePath = resolve(root, 'src/ui/README.md');

/** A dotted key in the tree, or null when any part is missing. */
export function lookup(tree: LangTree, key: string): string | null {
    let node: string | LangTree | undefined = tree;
    for (const part of key.split('.')) {
        if (node === undefined || typeof node === 'string') {
            return null;
        }
        node = node[part];
    }

    return typeof node === 'string' ? node : null;
}

export function renderReadme(words: LangTree): string {
    const word = (key: string): string => {
        const value = lookup(words, key);
        if (value === null) {
            throw new Error(`lang/en/ui_kit.json has no ${key}`);
        }

        return value;
    };

    const lines: string[] = [
        '# The components',
        '',
        '<!-- Generated by `npm run ui:readme` from src/showcase/manifest.ts and lang/en/ui_kit.json. Do not edit by hand. -->',
        '',
        'Every screen of an admin built on the kit is made of the components in this folder and nothing else. **Before writing markup, find the component here**, or open the host\'s UI Kit screen (the showcase, `KitPage`) to see it live with the snippet to copy and the props, slots and events. **No component fits? Add one to the kit** with its entry in `src/showcase/manifest.ts`, its words in `lang/*/ui_kit.json` and its demo, not styles on the page. Tailwind classes on a page lay the kit out (grid, gap, width, margin); they never draw an element (a button, a field, a badge, a table) of their own.',
        '',
        'The source of this file is the manifest (names, types, defaults, snippets) and `lang/en/ui_kit.json` (what each component is for and when to reach for it). `tests/ui/manifest.spec.ts` keeps the folder, the manifest, the words and this file in step.',
        '',
    ];

    for (const group of kitGroups) {
        lines.push(`## ${word(`groups.${group}.title`)}`, '', word(`groups.${group}.lead`), '', '| Component | Purpose | When to use |', '|---|---|---|');
        for (const entry of manifest.filter((candidate) => candidate.group === group)) {
            const name = entry.partOf ? `\`${entry.name}\` (with \`${entry.partOf}\`)` : `\`${entry.name}\``;
            lines.push(`| ${name} | ${word(`components.${entry.name}.purpose`)} | ${word(`components.${entry.name}.when`)} |`);
        }
        lines.push('');
    }

    lines.push('## Words', '', 'The words a component needs by itself (close, previous, loading) are in `lang/*/ui.json`, under the `ui.` keys; the words of a screen are the host\'s. A component never holds a literal.', '');

    return lines.join('\n');
}

export function currentReadme(): string {
    return renderReadme(JSON.parse(readFileSync(resolve(root, 'lang/en/ui_kit.json'), 'utf8')) as LangTree);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const rendered = currentReadme();
    if (process.argv.includes('--check')) {
        const onDisk = readFileSync(readmePath, 'utf8');
        if (onDisk !== rendered) {
            console.error('src/ui/README.md is stale: run npm run ui:readme');
            process.exit(1);
        }
        console.log('README is current');
    } else {
        writeFileSync(readmePath, rendered);
        console.log(`wrote ${readmePath}`);
    }
}
